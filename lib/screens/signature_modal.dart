import 'dart:math';
import 'dart:typed_data';
import 'package:flutter/material.dart';
import '../models/course.dart';
import '../models/student_profile.dart';
import '../services/png_encoder_service.dart';
import '../services/sowesign_api_service.dart';
import '../widgets/signature_pad.dart';

class SignatureModal extends StatefulWidget {
  final Course course;
  final StudentProfile profile;
  final VoidCallback onSignedSuccess;

  const SignatureModal({
    super.key,
    required this.course,
    required this.profile,
    required this.onSignedSuccess,
  });

  static Future<void> show({
    required BuildContext context,
    required Course course,
    required StudentProfile profile,
    required VoidCallback onSignedSuccess,
  }) {
    return showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: Colors.transparent,
      builder: (ctx) => SignatureModal(
        course: course,
        profile: profile,
        onSignedSuccess: onSignedSuccess,
      ),
    );
  }

  @override
  State<SignatureModal> createState() => _SignatureModalState();
}

class _SignatureModalState extends State<SignatureModal>
    with SingleTickerProviderStateMixin {
  late TabController _tabController;
  final GlobalKey<SignaturePadState> _padKey = GlobalKey<SignaturePadState>();

  List<List<Point<double>>> _touchStrokes = [];
  double _canvasWidth = 320;
  double _canvasHeight = 200;

  bool _isSubmitting = false;
  Uint8List? _autoGeneratedPng;

  @override
  void initState() {
    super.initState();
    _tabController = TabController(length: 2, vsync: this);
    // Pré-génération d'une signature réaliste unique pour le mode auto
    _autoGeneratedPng = PngEncoderService.generateOrganicSignaturePng();
  }

  @override
  void dispose() {
    _tabController.dispose();
    super.dispose();
  }

  void _regenerateAutoSignature() {
    setState(() {
      _autoGeneratedPng = PngEncoderService.generateOrganicSignaturePng();
    });
  }

  Future<void> _handleConfirmSigning() async {
    setState(() => _isSubmitting = true);

    Uint8List finalPngBytes;

    if (_tabController.index == 0) {
      // Mode Dessin tactile au doigt
      if (_padKey.currentState == null || _padKey.currentState!.isEmpty) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text('Veuillez tracer votre signature au doigt avant de valider.'),
            backgroundColor: Colors.orange,
          ),
        );
        setState(() => _isSubmitting = false);
        return;
      }
      finalPngBytes = PngEncoderService.renderTouchStrokesToPng(
        _touchStrokes,
        _canvasWidth,
        _canvasHeight,
      );
    } else {
      // Mode Génération automatique
      finalPngBytes = _autoGeneratedPng ??
          PngEncoderService.generateOrganicSignaturePng();
    }

    try {
      final result = await SoWeSignApiService.submitAttendance(
        profile: widget.profile,
        course: widget.course,
        customSignaturePng: finalPngBytes,
      );

      if (!mounted) return;
      setState(() => _isSubmitting = false);

      // Fermer le modal
      Navigator.pop(context);

      // Dialogue de confirmation de résultat
      showDialog(
        context: context,
        builder: (ctx) => AlertDialog(
          shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(20)),
          title: Row(
            children: [
              Icon(
                result.isDryRun ? Icons.shield_outlined : Icons.check_circle_rounded,
                color: result.isDryRun ? Colors.amber.shade700 : Colors.green,
                size: 28,
              ),
              const SizedBox(width: 10),
              Text(result.isDryRun ? 'Simulation Validée' : 'Émargement Réussi'),
            ],
          ),
          content: Text(
            result.message,
            style: const TextStyle(fontSize: 14, height: 1.4),
          ),
          actions: [
            TextButton(
              onPressed: () {
                Navigator.pop(ctx);
                widget.onSignedSuccess();
              },
              child: const Text('Fermer', style: TextStyle(fontWeight: FontWeight.bold)),
            ),
          ],
        ),
      );
    } catch (e) {
      if (!mounted) return;
      setState(() => _isSubmitting = false);
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('Erreur: ${e.toString()}'),
          backgroundColor: Colors.red.shade700,
        ),
      );
    }
  }

  @override
  Widget build(BuildContext context) {
    final isDryRun = widget.profile.isDryRun;

    return Container(
      decoration: const BoxDecoration(
        color: Colors.white,
        borderRadius: BorderRadius.vertical(top: Radius.circular(28)),
      ),
      padding: EdgeInsets.only(
        top: 20,
        left: 20,
        right: 20,
        bottom: MediaQuery.of(context).viewInsets.bottom + 24,
      ),
      child: Column(
        mainAxisSize: MainAxisSize.min,
        children: [
          // Poignée de glissement du modal
          Container(
            width: 40,
            height: 4,
            decoration: BoxDecoration(
              color: Colors.grey.shade300,
              borderRadius: BorderRadius.circular(2),
            ),
          ),
          const SizedBox(height: 16),

          // En-tête : Titre et badge de mode de sécurité
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Expanded(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    const Text(
                      'Émargement du cours',
                      style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold),
                    ),
                    const SizedBox(height: 2),
                    Text(
                      widget.course.title,
                      maxLines: 1,
                      overflow: TextOverflow.ellipsis,
                      style: TextStyle(fontSize: 13, color: Colors.grey.shade600),
                    ),
                  ],
                ),
              ),
              Container(
                padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 4),
                decoration: BoxDecoration(
                  color: isDryRun ? Colors.amber.shade50 : Colors.green.shade50,
                  borderRadius: BorderRadius.circular(12),
                  border: Border.all(
                    color: isDryRun ? Colors.amber.shade300 : Colors.green.shade300,
                  ),
                ),
                child: Row(
                  children: [
                    Icon(
                      isDryRun ? Icons.shield_rounded : Icons.flash_on_rounded,
                      size: 14,
                      color: isDryRun ? Colors.amber.shade800 : Colors.green.shade800,
                    ),
                    const SizedBox(width: 4),
                    Text(
                      isDryRun ? 'Dry-Run' : 'Mode Réel',
                      style: TextStyle(
                        fontSize: 11,
                        fontWeight: FontWeight.bold,
                        color: isDryRun ? Colors.amber.shade800 : Colors.green.shade800,
                      ),
                    ),
                  ],
                ),
              ),
            ],
          ),
          const SizedBox(height: 16),

          // Onglets : Dessin au doigt vs Génération automatique
          Container(
            height: 40,
            decoration: BoxDecoration(
              color: Colors.grey.shade100,
              borderRadius: BorderRadius.circular(12),
            ),
            child: TabBar(
              controller: _tabController,
              indicator: BoxDecoration(
                color: Colors.white,
                borderRadius: BorderRadius.circular(10),
                boxShadow: [
                  BoxShadow(
                    color: Colors.black.withOpacity(0.05),
                    blurRadius: 4,
                  ),
                ],
              ),
              labelColor: Colors.black87,
              unselectedLabelColor: Colors.grey.shade600,
              labelStyle: const TextStyle(fontSize: 13, fontWeight: FontWeight.w600),
              tabs: const [
                Tab(icon: Icon(Icons.draw_rounded, size: 16), text: 'Signer au doigt'),
                Tab(icon: Icon(Icons.auto_fix_high_rounded, size: 16), text: 'Automatique'),
              ],
            ),
          ),
          const SizedBox(height: 16),

          // Contenu selon l'onglet
          SizedBox(
            height: 220,
            child: TabBarView(
              controller: _tabController,
              children: [
                // 1. Pad interactif tactile
                SignaturePad(
                  key: _padKey,
                  onSignatureChanged: (strokes, w, h) {
                    _touchStrokes = strokes;
                    _canvasWidth = w;
                    _canvasHeight = h;
                  },
                ),

                // 2. Aperçu signature procédurale réaliste
                Container(
                  decoration: BoxDecoration(
                    color: Colors.grey.shade50,
                    borderRadius: BorderRadius.circular(16),
                    border: Border.all(color: Colors.grey.shade300),
                  ),
                  child: Center(
                    child: Column(
                      mainAxisAlignment: MainAxisAlignment.center,
                      children: [
                        const Icon(Icons.gesture_rounded, size: 48, color: Colors.blueAccent),
                        const SizedBox(height: 12),
                        const Text(
                          'Signature procédurale unique prête',
                          style: TextStyle(fontWeight: FontWeight.w600, fontSize: 14),
                        ),
                        const SizedBox(height: 4),
                        Text(
                          'Tracé Catmull-Rom organique & format WebKit 1-bit',
                          style: TextStyle(color: Colors.grey.shade600, fontSize: 12),
                        ),
                        const SizedBox(height: 12),
                        OutlinedButton.icon(
                          onPressed: _regenerateAutoSignature,
                          icon: const Icon(Icons.shuffle_rounded, size: 16),
                          label: const Text('Générer un autre tracé'),
                        ),
                      ],
                    ),
                  ),
                ),
              ],
            ),
          ),
          const SizedBox(height: 20),

          // Boutons d'action
          Row(
            children: [
              Expanded(
                child: OutlinedButton(
                  onPressed: _isSubmitting ? null : () => Navigator.pop(context),
                  style: OutlinedButton.styleFrom(
                    padding: const EdgeInsets.symmetric(vertical: 14),
                    shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
                  ),
                  child: const Text('Annuler'),
                ),
              ),
              const SizedBox(width: 12),
              Expanded(
                flex: 2,
                child: ElevatedButton(
                  onPressed: _isSubmitting ? null : _handleConfirmSigning,
                  style: ElevatedButton.styleFrom(
                    backgroundColor: isDryRun ? Colors.amber.shade700 : Colors.green.shade600,
                    foregroundColor: Colors.white,
                    padding: const EdgeInsets.symmetric(vertical: 14),
                    shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
                  ),
                  child: _isSubmitting
                      ? const SizedBox(
                          height: 20,
                          width: 20,
                          child: CircularProgressIndicator(
                            strokeWidth: 2,
                            color: Colors.white,
                          ),
                        )
                      : Text(
                          isDryRun ? 'Simuler l\'émargement' : 'Confirmer l\'émargement',
                          style: const TextStyle(fontWeight: FontWeight.bold),
                        ),
                ),
              ),
            ],
          ),
        ],
      ),
    );
  }
}
